-- 1) Legacy ручной привязки больше нет: продукт связывается с позицией ЕМИСС напрямую
--    (ingredients.emis_code), внешние карточки и маппинги не читаются никаким кодом.
ALTER TABLE ingredient_mappings DROP CONSTRAINT IF EXISTS ingredient_mappings_external_product_id_fkey;
DROP INDEX IF EXISTS idx_ingredient_mappings_external_name;
DROP INDEX IF EXISTS idx_ingredient_mappings_internal_ingredient_id;
DROP TABLE IF EXISTS ingredient_mappings;
DROP TABLE IF EXISTS external_products;

-- Рецепты, импортированные когда-то из OFF, остаются рецептами пользователя.
UPDATE recipes SET source = 'MANUAL' WHERE source = 'OFF';
UPDATE staging_recipes SET source = 'MANUAL' WHERE source = 'OFF';
-- Цены из OFF помечаем 'API' (машинный источник): данные не теряются, а синхронизация
-- ЕМИСС перезаписывает их наравне с ручными (EmisPriceApplier больше не щадит MANUAL
-- у привязанных продуктов).
UPDATE ingredient_prices SET source = 'API' WHERE source = 'OFF';
-- История синков и карточка провайдера OFF: функциональность удалена.
DELETE FROM sync_logs WHERE provider = 'OFF';
DELETE FROM integrations WHERE provider = 'OFF';

