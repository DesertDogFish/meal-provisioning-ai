-- name_norm пересчитывается формулой V8, иначе проверка дублей
-- existsByNameNormAndUnit() сработала бы по устаревшему ключу.
UPDATE ingredients SET name_norm =
  lower(btrim(regexp_replace(replace(replace(name, 'Ё', 'Е'), 'ё', 'е'), '\s+', ' ', 'g')))
 WHERE trip_id IS NULL;

