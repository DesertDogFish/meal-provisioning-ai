ALTER TABLE ingredient_prices DROP CONSTRAINT IF EXISTS ingredient_prices_source_check;
ALTER TABLE ingredient_prices ADD CONSTRAINT ingredient_prices_source_check
    CHECK (source IN ('MANUAL', 'ROSSTAT', 'API'));

-- 2) «Салфетки влажные, упаковка 20 шт.»: единица наблюдения ЕМИСС — УПАКОВКА, поэтому
--    цена ряда относится к упаковке целиком (amount=1), а не к одной салфетке.
UPDATE emis_products SET unit_kind = 'COUNT', unit_amount = 1, unit_scale = 'PCS'
 WHERE code IN ('6505', '6506', '6507', '6509') AND unit_kind <> 'COUNT';

-- 3) Названия — официальные формулировки ЕМИСС. Суффиксы фасовки у штучных продуктов
