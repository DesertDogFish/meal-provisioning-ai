-- История цен за 24 месяца для новых позиций (детерминированный сезонный дрейф, как в V13).
-- Для уже покрытых V13 ингредиентов ничего не делает (WHERE NOT EXISTS).
INSERT INTO ingredient_prices (ingredient_id, price_per_unit, currency, effective_from)
SELECT p.ingredient_id,
       ROUND(CAST(MAX(q.price_per_unit) * (1.0 + 0.03 * SIN(EXTRACT(MONTH FROM p.effective_from)::int * 1.1)) AS numeric), 2),
       'RUB',
       p.effective_from
FROM (
    SELECT i.id AS ingredient_id,
           (DATE_TRUNC('month', DATE '2026-10-01') - (n || ' month')::interval)::date AS effective_from
    FROM ingredients i
    CROSS JOIN generate_series(1, 24) AS n
) p
JOIN ingredient_prices q ON q.ingredient_id = p.ingredient_id
WHERE NOT EXISTS (
    SELECT 1 FROM ingredient_prices e
    WHERE e.ingredient_id = p.ingredient_id AND e.effective_from = p.effective_from
)
GROUP BY p.ingredient_id, p.effective_from
ON CONFLICT (ingredient_id, effective_from) DO NOTHING;
