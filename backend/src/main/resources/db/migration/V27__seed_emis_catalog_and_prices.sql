--
-- Источник: SDMX-выгрузки показателя 31448 (Средние потребительские цены на отдельные
-- виды продовольственных товаров):
--   * CodeList s_grtov «Виды товаров и услуг» — 885 позиций (в SDMX-ответе CodeLists
--     всегда полные, независимо от выбранных фильтров);
--   * Series региона 643004.АГ («Российская Федерация без учета новых субъектов
--     (с 01.01.2023)») — 562 товара × январь–апрель 2026 (2244 точки) и товары
--     105/106/111/112 × январь–апрель 2025 (16 точек) из более ранней выгрузки.
--
-- Единица измерения позиции ЕМИСС зашита в её название, поэтому разбирается на
-- unit_kind/unit_amount/unit_scale (см. V26): по ним цена приводится к единице продукта.
-- Повторный прогон безопасен: справочник — DO UPDATE (справочные данные), цены —
-- DO NOTHING (реальная синхронизация приоритетнее сида).

