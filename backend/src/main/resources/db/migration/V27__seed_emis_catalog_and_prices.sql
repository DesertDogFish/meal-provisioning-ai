-- Зачем: кнопка «Синхронизировать» ходит на fedstat.ru, а портал в проде отвечает
-- не всегда (анти-бот 403, троттлинг nginx 503, отказ при сужении оси «Год»).
-- Без сида приложение стартовало бы с пустым справочником: привязать продукт было бы
